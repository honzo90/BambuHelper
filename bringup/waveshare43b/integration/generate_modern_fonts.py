#!/usr/bin/env python3
"""Board-only smooth Inter fonts. Requires Pillow 12.3.0; no firmware dependency changes."""
from pathlib import Path
import struct
from PIL import ImageFont
ROOT=Path(__file__).resolve().parents[3]

def font_bytes(size, chars, bold=False):
    font=ImageFont.truetype(str(ROOT/('fonts/Inter-Bold.ttf' if bold else 'fonts/Inter-Regular.ttf')),size)
    ascent,descent=font.getmetrics()
    records=[];pixels=[]
    for cp in sorted(set(map(ord,chars))):
        mask,offset=font.getmask2(chr(cp),mode='L',anchor='ls')
        w,h=mask.size
        records.append(struct.pack('>IIIIiiI',cp,h,w,round(font.getlength(chr(cp))),-offset[1],offset[0],0))
        pixels.append(bytes(mask))
    return struct.pack('>IIIIII',len(records),6,size,0,ascent,descent)+b''.join(records)+b''.join(pixels)

def main():
    out=ROOT/'include/fonts/ws43b_modern.h'
    text=['// Generated by bringup/waveshare43b/integration/generate_modern_fonts.py',
          '// Source: existing fonts/Inter-Regular.ttf and Inter-Bold.ttf; Pillow 12.3.0. Board-only.',
          '#pragma once','#include <pgmspace.h>']
    for name,size,chars in [('ws43b_inter_digits',112,'0123456789:.-°C'),
                            ('ws43b_dash_large',72,'0123456789%.-'),
                            *[(f'ws43b_dash_{size}',size,''.join(chr(i) for i in range(32,127))+'ąćęłńóśźżĄĆĘŁŃÓŚŹŻ°·äöüÄÖÜßéèêàáâçñôûÉÇ') for size in (14,18,24,30)],
                            ('ws43b_inter_body',24,''.join(chr(i) for i in range(32,127))+'ąćęłńóśźżĄĆĘŁŃÓŚŹŻ°·äöüÄÖÜßéèêàáâçñôûÉÇ')]:
        data=font_bytes(size,chars,bold=name in ("ws43b_dash_large","ws43b_dash_30","ws43b_dash_18","ws43b_dash_24"))
        text.append(f'const uint8_t {name}[] PROGMEM = {{')
        text.extend('  '+', '.join(f'0x{v:02x}' for v in data[i:i+16])+',' for i in range(0,len(data),16))
        text.append('};');print(name,len(data))
    out.write_text('\n'.join(text)+'\n')
if __name__=='__main__':main()
