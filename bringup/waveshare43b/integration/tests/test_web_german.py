    def test_javascript_keeps_executable_tokens_endpoints_and_user_data(self):
        source = (ROOT / 'web/app.js').read_text()
        translated = loc.javascript(source, self.de, language='de')

        def executable(text):
            return [(kind, token) for _, kind, token in JavascriptLexer().get_tokens_unprocessed(text)
                    if kind not in (String.Single, String.Double)]

        def endpoints(text):
            return [ast.literal_eval(token) for _, kind, token in JavascriptLexer().get_tokens_unprocessed(text)
                    if kind in (String.Single, String.Double) and token[1:2] == '/']

        self.assertEqual(executable(source), executable(translated))
        self.assertEqual(endpoints(source), endpoints(translated))
        self.assertIn('esc(d.state)', translated)
        self.assertIn('d.name', translated)
        self.assertNotIn('MutationObserver', translated)
        fixture = 'const obj={"seconds":10}; let x=obj["seconds"]; let label="seconds";'
        out = loc.javascript(fixture, self.de, language='de')
        self.assertIn('"seconds":10', out)
        self.assertIn('obj["seconds"]', out)
        self.assertIn(json.dumps(self.de['seconds'], ensure_ascii=False), out)
        protocol = ('node.style.display=visible?"block":"none";'
                    'svg.setAttribute("fill","none");'
                    'const wire={"layer":"none"};'
                    'const prefix="BED";')
        self.assertEqual(protocol, loc.javascript(protocol, self.de, language='de'))
        file = self.directory / 'german.js'
        file.write_text(translated)
        run(['node', '--check', str(file)])

    def test_monitor_page_and_inline_javascript_are_german(self):
        server = (self.source / 'web_server.cpp').read_text()

        def page(name):
            declaration = re.search(r'\b' + name + r'\s*\[\s*\][^=]*=', server)
            self.assertIsNotNone(declaration, name)
            tail = server[declaration.end():]
            masked = loc.CPP.sub(lambda match: ' ' * len(match[0]), tail)
            initializer = tail[:masked.index(';')]
            chunks = []
            for match in loc.CPP.finditer(initializer):
                if match[0].startswith('R"'):
                    token = match[0]
                    begin = token.index('(') + 1
                    end = token.rindex(')' + match['delim'] + '"')
                    chunks.append(token[begin:end])
            return ''.join(chunks)

        german, english = page('MONITOR_PAGE_DE'), page('MONITOR_PAGE_EN')
        self.assertIn('lang="de"', german)
        self.assertEqual(Controls(english).controls, Controls(german).controls)
        for label in ('Waiting for data…', 'No connection to the panel',
                      'Save clock and idle settings', 'Printer is not configured'):
            polish_key = next(key for key, value in self.monitor_en.items() if value == label)
            self.assertIn(self.monitor_de[polish_key], german)
        en_scripts = re.findall(r'<script[^>]*>(.*?)</script>', english, re.S)
        de_scripts = re.findall(r'<script[^>]*>(.*?)</script>', german, re.S)
        self.assertEqual(len(en_scripts), len(de_scripts))
        for index, (before, after) in enumerate(zip(en_scripts, de_scripts)):
            def endpoint_strings(text):
                return [ast.literal_eval(token) for _, kind, token in JavascriptLexer().get_tokens_unprocessed(text)
                        if kind in (String.Single, String.Double) and token[1:2] == '/']
            self.assertEqual(endpoint_strings(before), endpoint_strings(after))
            file = self.directory / ('monitor-de-' + str(index) + '.js')
            file.write_text(after)
            run(['node', '--check', str(file)])

