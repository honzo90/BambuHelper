def run(command, **kwargs):
    result = subprocess.run(command, text=True, capture_output=True, **kwargs)
    if result.returncode:
        raise AssertionError(result.stdout + result.stderr)
    return result


class Controls(HTMLParser):
    def __init__(self, source):
        super().__init__(convert_charrefs=True)
        self.controls = []
        self.feed(source)

    def handle_starttag(self, tag, attrs):
        mutable = {'lang', 'title', 'placeholder', 'aria-label', 'alt'}
        self.controls.append((tag, [(k, v) for k, v in attrs if k not in mutable]))


def function_definition(source, name):
    """Brace-aware extraction; ignore braces inside literals and comments."""
    match = re.search(r'(?:static\s+)?(?:void|function)\s+' + re.escape(name)
                      + r'\s*\([^)]*\)\s*\{', source)
    if not match:
        raise AssertionError('Function not found: ' + name)
    start = match.end() - 1
    # Pygments handles ordinary literals, comments and template strings.
    depth = 0
    for position, kind, token in JavascriptLexer().get_tokens_unprocessed(source[start:]):
        if kind in String or kind in Comment:
            continue
        for offset, char in enumerate(token):
            if char == '{':
                depth += 1
            elif char == '}':
                depth -= 1
                if depth == 0:
                    return source[match.start():start + position + offset + 1]
    raise AssertionError('Unclosed function: ' + name)


def gzip_header(path, prefix):
    header = path.read_text()
    array = re.search(re.escape(prefix) + r'_APP_JS_GZ\s*\[\s*\][^{]*\{([^}]+)\}', header, re.S)
    version = re.search(r'#define\s+' + re.escape(prefix) + r'_APP_JS_VER\s+"([0-9a-fA-F]{8})"', header)
    if not array or not version:
        raise AssertionError('Missing gzip array/version in ' + str(path))
    blob = bytes(int(value.strip(), 0) for value in array[1].split(',') if value.strip())
    decoded = gzip.decompress(blob)
    if version[1].lower() != format(zlib.crc32(decoded) & 0xffffffff, '08x'):
        raise AssertionError('JS CRC does not describe the served bytes')
    return decoded, version[1]


class GermanWeb(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.temp = tempfile.TemporaryDirectory()
        cls.addClassCleanup(cls.temp.cleanup)
        cls.directory = Path(cls.temp.name)
        cls.source = cls.directory / 'src'
        cls.source.mkdir()
