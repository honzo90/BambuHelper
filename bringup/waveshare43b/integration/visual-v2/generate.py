#!/usr/bin/env python3
"""Encode checked Chromium RGBA into bounded, transparent-skip RGB565 rows.

No image manipulation: rasterize.cjs supplies exact approved SVG viewport pixels.
Add asset metadata to assets.json, rerun rasterize.cjs, then this standard-library
generator. Source SVG/PNG, raster RGBA and generator hashes accompany the output.
"""
from pathlib import Path
import hashlib
import json
import struct

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
OUTPUT = ROOT / 'include/ws43b_visual_assets_data.h'

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def rgb565(r, g, b):
    return (r >> 3) << 11 | (g >> 2) << 5 | b >> 3

def material(r, g, b):
    # Source-colour mask only: cool/neutral metal and flanges are never tinted.
    return int(g - r >= 8 and g - b >= 7 and g * 100 >= r * 108 and g * 100 >= b * 108)

def source_dimensions(path):
    if path.suffix == '.png':
        header = path.read_bytes()[:24]
        if header[:8] != b'\x89PNG\r\n\x1a\n' or header[12:16] != b'IHDR':
            raise ValueError('Invalid source PNG header')
        return list(struct.unpack('>II', header[16:24]))
    return None

def encode(asset, rgba):
    width, height = asset['width'], asset['height']
    if not (1 <= width <= 256 and 1 <= height <= 1024):
        raise ValueError('Unsupported sprite dimensions')
    if len(rgba) != width * height * 4:
        raise ValueError('Unexpected raw RGBA dimensions')
    offsets, data, tinted = [0], bytearray(), 0
    for y in range(height):
        x, previous_end = 0, 0
        while x < width:
            if rgba[(y * width + x) * 4 + 3] == 0:
                x += 1
                continue
            begin = x
            pixel = rgba[(y * width + x) * 4:(y * width + x + 1) * 4]
            mask = material(*pixel[:3]) if asset.get('green_material') else 0
            while x < width and rgba[(y * width + x) * 4 + 3]:
                pixel = rgba[(y * width + x) * 4:(y * width + x + 1) * 4]
                if (material(*pixel[:3]) if asset.get('green_material') else 0) != mask:
                    break
                x += 1
            data.extend(struct.pack('<HH', begin - previous_end, (x - begin) | (mask << 15)))
            for at in range(begin, x):
                r, g, b, alpha = rgba[(y * width + at) * 4:(y * width + at + 1) * 4]
                tinted += mask
                data.extend(struct.pack('<HB', rgb565(r, g, b), alpha))
            previous_end = x
        offsets.append(len(data))
    return offsets, data, tinted

def main():
    config = json.loads((HERE / 'assets.json').read_text())
    assets = config['assets']
    names = [asset['name'] for asset in assets]
    if len(names) != len(set(names)):
        raise ValueError('Duplicate asset name')
    lines = ['// Generated by visual-v2/generate.py; do not edit.', '#pragma once',
             'enum class Asset : uint8_t { ' + ', '.join(names) + ', Count };', '']
    records, total = [], 0
    for asset in assets:
        name = asset['name']
        rgba_path = HERE / 'rasterized' / (name + '.rgba')
        offsets, data, tinted = encode(asset, rgba_path.read_bytes())
        lines.append(f'static constexpr uint32_t k{name}Rows[] = {{' + ','.join(map(str, offsets)) + '};')
        lines.append(f'static constexpr uint8_t k{name}Data[] = {{')
        lines += ['  ' + ','.join(f'0x{b:02x}' for b in data[i:i+24]) + ',' for i in range(0, len(data), 24)]
        lines += ['};', f'static constexpr Sprite k{name} = {{{asset["width"]}, {asset["height"]}, k{name}Rows, {len(offsets)}, k{name}Data, sizeof(k{name}Data)}};', '']
        total += len(data) + 4 * len(offsets)
        records.append({**asset, 'source_sha256':sha(HERE / asset['source']),
                        'source_pixel_dimensions':source_dimensions(HERE / asset['source']),
                        'rgba_sha256':sha(rgba_path), 'png_sha256':sha(HERE / 'rasterized' / (name + '.png')),
                        'encoded_bytes':len(data), 'row_offset_bytes':4 * len(offsets), 'material_pixels':tinted})
    # First eight approved sprites must remain within their flash allowance;
    # a future larger scene should have its own explicit size budget.
    first_eight = sum(r['encoded_bytes'] + r['row_offset_bytes'] for r in records[:8])
    if first_eight >= 65 * 1024:
        raise ValueError('Eight-asset flash budget exceeded')
    scene_names = {'Model', 'Plate', 'Head'}
    scene_bytes = sum(r['encoded_bytes'] + r['row_offset_bytes'] for r in records if r['name'] in scene_names)
    if scene_bytes >= 100 * 1024:
        raise ValueError('Scene-component flash budget exceeded')
    if total - first_eight - scene_bytes >= 32 * 1024:
        raise ValueError('Shared-control icon flash budget exceeded')
    if total >= 165 * 1024:
        raise ValueError('Total visual-asset flash budget exceeded')
    lines += ['static constexpr Sprite kEmptySprite = {0,0,nullptr,0,nullptr,0};',
              'inline const Sprite &descriptor(Asset asset) {', '  switch (asset) {']
    lines += [f'    case Asset::{name}: return k{name};' for name in names]
    lines += ['    default: return kEmptySprite;', '  }', '}', '']
    OUTPUT.write_text('\n'.join(lines))
    manifest = {'format':'row-skip16-run15-material1-rgb565le-alpha8-v1', 'source_reference':config['source_reference'],
                'pixel_order':'RGB565 host value after little-endian byte decode; alpha is straight/unpremultiplied',
                'material_rule':'g-r >= 8, g-b >= 7, g >= 1.08*r, g >= 1.08*b; only opted-in source assets',
                'recolor_rule':'source RGB565 maximum channel modulates requested RGB565 tint; nonmaterial pixels unchanged',
                'svg_meet_note':'Spool uses SVG image 1280x1280 even though original PNG dimensions are 1254x1254, matching approved HTML.',
                'assets':records,'total_encoded_and_offsets_bytes':total,
                'generated_header':str(OUTPUT.relative_to(ROOT)),'generated_header_sha256':sha(OUTPUT),
                'pipeline_sha256':{p.name:sha(p) for p in [HERE/'assets.json',HERE/'generate.py',HERE/'rasterize.cjs',HERE/'rasterizer.json']}}
    (HERE / 'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps({'assets':len(assets),'encoded_and_offsets_bytes':total,'output':str(OUTPUT)}))

if __name__ == '__main__':
    main()
