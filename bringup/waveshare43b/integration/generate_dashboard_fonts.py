#!/usr/bin/env python3
"""Generate bounded Inter VLW assets for the native 800x480 dashboard v2.

Uses the same Pillow mask/metrics and VLW v6 layout as generate_modern_fonts.py.
Requires Pillow 12.3.0. Fonts stay in flash; this generator adds no runtime code.
"""
from pathlib import Path
import argparse
import hashlib
import struct
from PIL import ImageFont, __version__ as PILLOW_VERSION

ROOT = Path(__file__).resolve().parents[3]
OUTPUT = ROOT / 'include/fonts/ws43b_dashboard_v2.h'
REQUIRED_PILLOW = '12.3.0'
MAX_BYTES = 180 * 1024
UI_CHARACTERS = (''.join(chr(i) for i in range(32, 127))
                 + 'ąćęłńóśźżĄĆĘŁŃÓŚŹŻ°·äöüÄÖÜßéèêàáâçñôûÉÇ–—…')
FONT_SPECS = [
    ('ws43b_v2_12', 12, UI_CHARACTERS, False),
    ('ws43b_v2_13', 13, UI_CHARACTERS, False),
    *[(f'ws43b_v2_b{size}', size, UI_CHARACTERS, True)
      for size in (14, 15, 16, 17, 25)],
    ('ws43b_v2_b23', 23, '0123456789%- ', True),
    ('ws43b_v2_b28', 28, '0123456789:.,-+ hmind', True),
    ('ws43b_v2_b29', 29, '0123456789%.,:-+°C ', True),
    ('ws43b_v2_b64', 64, '0123456789- ', True),
    ('ws43b_v2_b43', 43, '%', True),
]


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def font_bytes(size, characters, bold):
    """VLW v6: six big-endian header words, 28-byte records, 8-bit alpha masks."""
    font = ImageFont.truetype(str(ROOT / ('fonts/Inter-Bold.ttf' if bold
                                        else 'fonts/Inter-Regular.ttf')), size)
    ascent, descent = font.getmetrics()
    records, pixels = [], []
    for codepoint in sorted(set(map(ord, characters))):
        character = chr(codepoint)
        mask, offset = font.getmask2(character, mode='L', anchor='ls')
        width, height = mask.size
        records.append(struct.pack('>IIIIiiI', codepoint, height, width,
                                   round(font.getlength(character)),
                                   -offset[1], offset[0], 0))
        pixels.append(bytes(mask))
    return (struct.pack('>IIIIII', len(records), 6, size, 0, ascent, descent)
            + b''.join(records) + b''.join(pixels))


def generate():
    if PILLOW_VERSION != REQUIRED_PILLOW:
        raise SystemExit(f'Pillow {REQUIRED_PILLOW} required; found {PILLOW_VERSION}')
    script = Path(__file__).resolve()
    text = [
        '// Generated by bringup/waveshare43b/integration/generate_dashboard_fonts.py',
        '// Source: repository Inter-Regular.ttf and Inter-Bold.ttf; existing Inter font provenance/license applies.',
        f'// Pillow: {PILLOW_VERSION}; FreeType: {ImageFont.core.freetype2_version}; VLW: 6; grayscale antialiasing.',
        f'// Generator SHA256: {sha256(script)}',
        *[f'// {name} SHA256: {sha256(ROOT / name)}'
          for name in ('fonts/Inter-Regular.ttf', 'fonts/Inter-Bold.ttf')],
        '// Full UI coverage: 12, 13, b14, b15, b16, b17, b25 (ASCII, Polish, supported Latin accents, punctuation).',
        '// Restricted: b23=percent/digits/dash/space; b43=%; b28=time digits + h/m/i/n/d; b29=temperatures/numeric; b64=progress digits/dash/space.',
        '// Pixel masks are stored once in PROGMEM. No runtime generation or per-frame allocation is added.',
        '#pragma once', '#include <pgmspace.h>',
    ]
    sizes = {}
    for name, size, characters, bold in FONT_SPECS:
        data = font_bytes(size, characters, bold)
        sizes[name] = len(data)
        text.append(f'// {size}px {"Bold" if bold else "Regular"}; {len(set(characters))} glyphs; {len(data)} bytes; SHA256 {hashlib.sha256(data).hexdigest()}')
        text.append(f'const uint8_t {name}[] PROGMEM = {{')
        text.extend('  ' + ', '.join(f'0x{value:02x}' for value in data[i:i+16]) + ','
                    for i in range(0, len(data), 16))
        text.append('};')
    total = sum(sizes.values())
    if total > MAX_BYTES:
        raise SystemExit(f'Font payload {total} exceeds the {MAX_BYTES}-byte flash budget')
    text.append(f'// Total VLW font payload: {total} bytes (budget: {MAX_BYTES} bytes).')
    return '\n'.join(text) + '\n', sizes


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=OUTPUT)
    parser.add_argument('--check', action='store_true', help='Verify byte-identical output without writing')
    args = parser.parse_args()
    text, sizes = generate()
    if args.check:
        if args.output.read_text() != text:
            raise SystemExit('Generated dashboard fonts differ from the saved header')
    else:
        args.output.write_text(text)
    for name, count in sizes.items():
        print(f'{name}: {count} bytes')
    print(f'TOTAL: {sum(sizes.values())} bytes / {MAX_BYTES}')


if __name__ == '__main__':
    main()
